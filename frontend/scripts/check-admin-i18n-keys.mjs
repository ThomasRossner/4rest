import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const frontendRoot = path.resolve(__dirname, '..');
const localesPath = path.join(frontendRoot, 'src', 'locales', 'de', 'translation.json');

if (!fs.existsSync(localesPath)) {
  console.error('Locale file not found:', localesPath);
  process.exit(2);
}
const translation = JSON.parse(fs.readFileSync(localesPath, 'utf8'));

function getAtPath(obj, keyPath) {
  const parts = keyPath.split('.');
  let cur = obj;
  for (const p of parts) {
    if (cur == null || typeof cur !== 'object') return undefined;
    cur = cur[p];
  }
  return cur;
}

function hasKey(keyPath) {
  const v = getAtPath(translation, keyPath);
  return typeof v === 'string';
}

